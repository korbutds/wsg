'use strict';

// User-level files for the agents: the `wsg-new` skill lets any Claude Code session create a
// workspace when asked; the `wsg-advisor` agent checks a workspace agent's questions before they
// reach the owner (docs/advisor-guide.md). They live in the user's own config directories, so wsg overwrites or
// removes only a file it wrote itself — recognised by the marker — and refuses anything else.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const T = require('./templates');

const MARKER = '<!-- generated by wsg -->';
// A TOML file has no HTML comments: the same words as a comment line.
const TOML_MARKER = '# generated by wsg';
const markerOf = (item) => (item.dest.endsWith('.toml') ? TOML_MARKER : MARKER);

// The config directories, as each tool finds its own. An empty variable counts as unset.
const home = (env) => env.HOME || os.homedir();
const configDir = (env = process.env) => env.CLAUDE_CONFIG_DIR || path.join(home(env), '.claude');
const codexDir = (env = process.env) => env.CODEX_HOME || path.join(home(env), '.codex');
const ROOTS = { claude: configDir, codex: codexDir };

// name: what it is called; rel: the template under templates/; dest: where it goes under root.
const ITEMS = [
  { name: 'wsg-new', rel: 'claude/wsg-new/SKILL.md', dest: 'skills/wsg-new/SKILL.md', root: 'claude' },
  { name: 'wsg-advisor', rel: 'claude/agents/wsg-advisor.md', dest: 'agents/wsg-advisor.md', root: 'claude' },
];

const skillsDir = (env = process.env) => path.join(configDir(env), 'skills');
const fileOf = (item, env) => path.join(ROOTS[item.root](env), item.dest);

function read(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (e) {
    if (e.code === 'ENOENT') return null;
    throw e;
  }
}

// [{ item, file, status: 'missing'|'unmarked'|'outdated'|'current' }]
function status(env = process.env, items = ITEMS) {
  return items.map((item) => {
    const file = fileOf(item, env);
    const cur = read(file);
    const body = T.template(item.rel);
    let st;
    if (cur === null) st = 'missing';
    else if (cur === body) st = 'current';
    else if (!cur.includes(markerOf(item))) st = 'unmarked';
    else st = 'outdated';
    return { item, file, status: st };
  });
}

// Returns [{ file, status: 'written'|'unchanged'|'refused' }].
function install(env = process.env) {
  return status(env).map(({ item, file, status: st }) => {
    if (st === 'current') return { file, status: 'unchanged' };
    if (st === 'unmarked') return { file, status: 'refused' };
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, T.template(item.rel));
    return { file, status: 'written' };
  });
}

// Returns [{ file, status: 'removed'|'absent'|'kept' }]. A skill's own directory goes with it
// when nothing else is left there; the shared skills/ or agents/ directory never does.
function uninstall(env = process.env) {
  return status(env).map(({ item, file, status: st }) => {
    if (st === 'missing') return { file, status: 'absent' };
    if (st === 'unmarked') return { file, status: 'kept' };
    fs.unlinkSync(file);
    const dir = path.dirname(file);
    if (item.dest.split('/').length > 2 && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
    return { file, status: 'removed' };
  });
}

module.exports = { MARKER, TOML_MARKER, ITEMS, configDir, codexDir, skillsDir, status, install, uninstall };

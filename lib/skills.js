'use strict';

// User-level files for the agents: the `wsg-new` skill lets any Claude Code session create a
// workspace when asked; the `wsg-advisor` agent checks a workspace agent's questions before they
// reach the owner (docs/advisor-guide.md). They live in the user's own config directories, so wsg overwrites or
// removes only a file it wrote itself — recognised by the marker — and refuses anything else.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const T = require('./templates');
const { onPath } = require('./launch');

const MARKER = '<!-- generated by wsg -->';
// A TOML file has no HTML comments: the same words as a comment line.
const TOML_MARKER = '# generated by wsg';
const markerOf = (item) => (item.dest.endsWith('.toml') ? TOML_MARKER : MARKER);

// The config directories, as each tool finds its own. An empty variable counts as unset.
const home = (env) => env.HOME || os.homedir();
const configDir = (env = process.env) => env.CLAUDE_CONFIG_DIR || path.join(home(env), '.claude');
const codexDir = (env = process.env) => env.CODEX_HOME || path.join(home(env), '.codex');
const ROOTS = { claude: configDir, codex: codexDir };
// Codex is there when it says where its home is, has one, or can be run. Without it, its agent is
// not installed: a ~/.codex made for a tool the user doesn't have would only confuse.
const codexPresent = (env = process.env) => !!env.CODEX_HOME || fs.existsSync(path.join(home(env), '.codex')) || onPath('codex', env);
const PRESENT = { claude: () => true, codex: codexPresent };

// name: what it is called; rel: the template under templates/; dest: where it goes under root.
const ITEMS = [
  { name: 'wsg-new', rel: 'claude/wsg-new/SKILL.md', dest: 'skills/wsg-new/SKILL.md', root: 'claude' },
  { name: 'wsg-advisor', rel: 'claude/agents/wsg-advisor.md', dest: 'agents/wsg-advisor.md', root: 'claude' },
  { name: 'wsg-advisor', rel: 'codex/agents/wsg-advisor.toml', dest: 'agents/wsg-advisor.toml', root: 'codex' },
];

const skillsDir = (env = process.env) => path.join(configDir(env), 'skills');

// The Claude Code advisor's hook runs the guard of this very package: `<GUARD>` in the template
// becomes its absolute path. The hook command is `node "<path>" || exit 2` in a YAML '…' string,
// so the path is escaped for the shell's "…" first, then for YAML ('' for ').
const GUARD = path.join(__dirname, 'advisor-guard.js');
const PLACEHOLDER = '<GUARD>';
// Both advisors run wsg as `node "<WSG_CLI>"`: this package's CLI by its absolute path, the only
// wsg the guard lets through (it takes the path from its own location), never one from PATH or
// npx. In the body, so escaped for the shell's "…" only. A path with `$` or a backtick is
// rendered, but the guard blocks any command that holds one: such an advisor cannot run wsg.
const WSG_CLI = path.join(__dirname, '..', 'bin', 'cli.js');
const CLI_PLACEHOLDER = '<WSG_CLI>';
const shellQuoted = (p) => p.replace(/[\\"$`]/g, '\\$&');
const quoteGuard = (p) => shellQuoted(p).replace(/'/g, "''");
const render = (item, guard = GUARD, cli = WSG_CLI) => T.template(item.rel)
  .split(PLACEHOLDER).join(quoteGuard(guard))
  .split(CLI_PLACEHOLDER).join(shellQuoted(cli));
// The guard paths an installed file runs, as the shell will see them.
function guardsOf(text) {
  return [...text.matchAll(/^\s*command: 'node "((?:[^"\\]|\\.)*)" \|\| exit 2'\s*$/gm)]
    .map((m) => m[1].replace(/''/g, "'").replace(/\\(.)/g, '$1'));
}
const fileOf = (item, env) => path.join(ROOTS[item.root](env), item.dest);

function read(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (e) {
    if (e.code === 'ENOENT') return null;
    throw e;
  }
}

// [{ item, file, status: 'missing'|'unmarked'|'outdated'|'broken'|'current', guard? }]
// broken: ours, but the guard its hook runs is gone (the package moved or was removed), so every
// tool call of the advisor is blocked; guard is that path.
function status(env = process.env, items = ITEMS) {
  return items.map((item) => {
    const file = fileOf(item, env);
    const cur = read(file);
    const body = render(item);
    let st;
    let guard;
    if (cur === null) st = 'missing';
    else if (cur === body) st = 'current';
    else if (!cur.includes(markerOf(item))) st = 'unmarked';
    else {
      guard = guardsOf(cur).find((g) => !fs.existsSync(g));
      st = guard ? 'broken' : 'outdated';
    }
    return guard ? { item, file, status: st, guard } : { item, file, status: st };
  });
}

// Returns [{ file, status: 'written'|'unchanged'|'refused'|'skipped' }]; skipped: the tool is absent.
function install(env = process.env) {
  return status(env).map(({ item, file, status: st }) => {
    if (!PRESENT[item.root](env)) return { file, status: 'skipped', tool: item.root };
    if (st === 'current') return { file, status: 'unchanged' };
    if (st === 'unmarked') return { file, status: 'refused' };
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, render(item));
    return { file, status: 'written' };
  });
}

// Returns [{ file, status: 'removed'|'absent'|'kept' }]. A skill's own directory goes with it
// when nothing else is left there; the shared skills/ or agents/ directory never does.
function uninstall(env = process.env) {
  return status(env).map(({ item, file, status: st }) => {
    if (st === 'missing') return { file, status: 'absent' };
    if (st === 'unmarked') return { file, status: 'kept' };
    fs.unlinkSync(file);
    const dir = path.dirname(file);
    if (item.dest.split('/').length > 2 && fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
    return { file, status: 'removed' };
  });
}

module.exports = { MARKER, TOML_MARKER, ITEMS, GUARD, WSG_CLI, configDir, codexDir, codexPresent, skillsDir, render, guardsOf, status, install, uninstall };

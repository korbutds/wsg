'use strict';

// User-level skills for Claude Code: `wsg-new` lets any session create a workspace when asked.
// They live in the user's own skills directory, so wsg overwrites only a file it wrote itself —
// recognised by the marker — and refuses anything else.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const T = require('./templates');

const MARKER = '<!-- generated by wsg -->';
const SKILLS = ['wsg-new'];

const skillsDir = (env = process.env) =>
  path.join(env.CLAUDE_CONFIG_DIR || path.join(env.HOME || os.homedir(), '.claude'), 'skills');

// Returns [{ file, status: 'written'|'unchanged'|'refused' }].
function install(env = process.env) {
  return SKILLS.map((name) => {
    const body = T.template(`claude/${name}/SKILL.md`);
    const file = path.join(skillsDir(env), name, 'SKILL.md');
    let cur = null;
    try {
      cur = fs.readFileSync(file, 'utf8');
    } catch (e) {
      if (e.code !== 'ENOENT') throw e;
    }
    if (cur === body) return { file, status: 'unchanged' };
    if (cur !== null && !cur.includes(MARKER)) return { file, status: 'refused' };
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body);
    return { file, status: 'written' };
  });
}

module.exports = { MARKER, SKILLS, skillsDir, install };
